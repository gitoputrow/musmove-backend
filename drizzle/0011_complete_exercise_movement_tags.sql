-- Fail if an unexpected/unmapped exercise still lacks tags; do not hide the
-- problem by assigning an arbitrary default. Inserts must supply tags too.
ALTER TABLE exercise_catalog
  ALTER COLUMN movement_tags SET NOT NULL,
  ADD CONSTRAINT exercise_catalog_movement_tags_valid CHECK (
    array_ndims(movement_tags) = 1
    AND cardinality(movement_tags) BETWEEN 1 AND 11
    AND array_position(movement_tags, NULL) IS NULL
    AND movement_tags <@ ARRAY['shoulder', 'elbow', 'wrist', 'back', 'hip', 'knee', 'ankle', 'floor_transfer', 'overhead_reach', 'deep_knee_bend', 'balance_challenge']::text[]
  );
