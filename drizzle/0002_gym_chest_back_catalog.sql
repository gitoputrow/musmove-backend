FROM requested
WHERE NOT EXISTS (
  SELECT 1 FROM exercise_catalog existing
  WHERE existing.mode = 'gym'
    AND (existing.id = requested.id OR lower(trim(existing.en_label)) = lower(trim(requested.en_label)))
)
